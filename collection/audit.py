"""Audit one fresh collection without mixing regimes or treating reward as step truth."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path

from collection.run_tau2 import write_json
from gibs.graph.step_graph import build_step_graph
from gibs.validation.dataset_audit import canon


def audit(data):
    tasks = {str(t['id']): t for t in data.get('tasks', [])}
    seen, content, rows = set(), set(), []
    totals, per_task = Counter(), defaultdict(Counter)
    for sim in data.get('simulations', []):
        if sim['id'] in seen:
            totals['duplicate_uuid_records'] += 1
            continue
        seen.add(sim['id'])
        tid = str(sim['task_id'])
        digest = canon(sim)
        if (tid, digest) in content:
            totals['duplicate_content_extra_copies'] += 1
        content.add((tid, digest))
        reward = (sim.get('reward_info') or {}).get('reward')
        outcome = 'infrastructure_error' if reward is None else 'success' if reward >= .5 else 'failure'
        totals[outcome] += 1
        per_task[tid][outcome] += 1
        messages = sim.get('messages') or []
        calls = [c for m in messages if m.get('role') == 'assistant' for c in (m.get('tool_calls') or [])]
        called = {c['name'] for c in calls}
        expected = {a['name'] for a in (tasks.get(tid, {}).get('evaluation_criteria') or {}).get('actions', [])}
        missing = sorted(expected - called)
        if reward is not None and reward >= .5 and missing:
            totals['reward_success_missing_expected_tool_names'] += 1
            per_task[tid]['reward_success_missing_expected_tool_names'] += 1
        # Tool names alone do not verify arguments, policy compliance, or a
        # customer's behavior. This is a review flag, never a replacement reward.
        compatible = False
        error = None
        steps = 0
        try:
            graph = build_step_graph(sim, None, tasks.get(tid))
            steps = sum(n['type'] == 'AgentStep' for n in graph['nodes'])
            compatible = True
        except ValueError as exc:
            error = str(exc)
            totals['unbuildable_graphs'] += 1
        served_models = sorted({m['raw_data'].get('model', 'unknown') for m in messages if m.get('raw_data')})
        choices = [m['raw_data']['choices'][0] for m in messages
                   if (m.get('raw_data') or {}).get('choices')]
        reasoning_responses = sum(bool(c['message'].get('reasoning') or c['message'].get('reasoning_content')) for c in choices)
        length_stops = sum(c.get('finish_reason') == 'length' for c in choices)
        totals['responses_with_reasoning'] += reasoning_responses
        totals['output_limit_stops'] += length_stops
        tokens = Counter()
        for m in messages:
            for key in ('prompt_tokens', 'completion_tokens'):
                tokens[key] += (m.get('usage') or {}).get(key, 0)
        totals.update(tokens)
        rows.append({'run_id': sim['id'], 'task_id': tid, 'content_hash': digest,
                     'official_outcome': outcome, 'official_reward': reward,
                     'termination': sim.get('termination_reason'), 'served_models': served_models,
                     'responses_with_reasoning': reasoning_responses, 'output_limit_stops': length_stops,
                     'agent_steps': steps, 'tool_calls': len(calls),
                     'parallel_call_turns': sum(len(m.get('tool_calls') or []) > 1 for m in messages if m.get('role') == 'assistant'),
                     'tool_errors': sum(m.get('role') == 'tool' and bool(m.get('error')) for m in messages),
                     'missing_expected_tool_names': missing, 'graph_compatible': compatible,
                     'graph_error': error, 'tokens': dict(tokens)})
    return {'unique_runs': len(seen), 'distinct_task_content_classes': len(content), 'totals': dict(totals),
            'per_task': {t: dict(v) for t, v in sorted(per_task.items(), key=lambda x: int(x[0]))},
            'notes': ['Success is the unmodified benchmark reward, not human-verified correctness.',
                      'Missing expected tool names are review flags; arguments and alternative valid solutions are not evaluated here.',
                      'No human labels or GIBS/C4 targets are generated by this audit.'],
            'runs': rows}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args(argv)
    path = args.input / 'results.json' if args.input.is_dir() else args.input
    payload = path.read_bytes()
    result = audit(json.loads(payload))
    result['input_sha256'] = hashlib.sha256(payload).hexdigest()
    out = args.output or path.parent / 'audit.json'
    write_json(out, result)
    print(json.dumps({k: result[k] for k in ('unique_runs', 'distinct_task_content_classes', 'totals')}, indent=2))


if __name__ == '__main__':
    main()
